from __future__ import annotations

from typing import Any, Protocol

from ..domain.source import Contribution


class MetadataPort(Protocol):
    """知识库配置、资料、任务及来源贡献协议；事务由适配器内部完成。"""

    async def ready(self) -> bool: ...
    async def kb(self, kb_id: str) -> dict[str, Any]: ...
    async def list_kbs(self) -> list[dict[str, Any]]: ...
    async def create_kb(self, name: str, model: dict, profile: dict) -> dict: ...

    async def document(self, kb_id: str, document_id: str) -> dict: ...
    async def document_exists(self, document_id: str) -> bool: ...
    async def documents(
        self, kb_id: str, active: bool | None = None, limit: int = 100, offset: int = 0
    ) -> list[dict]: ...
    async def list_documents(
        self, kb_id: str, active: bool | None = None, limit: int = 100, offset: int = 0
    ) -> list[dict]: ...
    async def active_documents(self, kb_id: str) -> list[dict]: ...
    async def document_jobs(self, kb_id: str, document_id: str) -> list[dict]: ...
    async def jobs_for_kb(self, kb_id: str) -> list[dict]: ...

    async def request(self, kb_id: str, operation: str, key: str) -> dict | None: ...
    async def register_upload(self, doc: dict, input_data: dict, key: str, request_data: dict) -> dict:
        """同一短事务登记资料、导入任务与幂等请求，返回实际登记结果。"""
        ...

    async def enqueue(
        self,
        kb_id: str,
        operation: str,
        document_id: str | None,
        input_data: dict,
        key: str,
        request_data: dict,
    ) -> str: ...
    async def job(self, job_id: str) -> dict: ...
    async def update_job(self, job_id: str, **fields: Any) -> None: ...
    async def maintenance(self, kb_id: str, state: str, job_id: str | None) -> None: ...
    async def claim(self, now: float) -> dict | None:
        """原子领取可执行任务；未完成写入的恢复任务优先于新任务。"""
        ...

    async def retry(self, job_id: str, key: str) -> bool: ...

    async def contributions(
        self, kb_id: str, document_ids: list[str] | None = None, *, contribution_ids: list[str] | None = None
    ) -> list[Contribution]:
        """按来源和贡献 ID 取交集，供合并、范围查询及证据回查。"""
        ...

    async def replace_contributions(
        self, kb_id: str, contributions: list[Contribution], issues: list[dict], issue_documents: list[str]
    ) -> None: ...
    async def finish(self, job_id: str, plan: dict) -> None:
        """按持久化计划提交最终元数据状态，并恢复知识库可查询状态。"""
        ...

    async def candidate_issues(self, job_id: str, limit: int, offset: int) -> list[dict]: ...

    async def expired_checkpoints(self, threshold: str) -> list[dict]: ...
    async def referenced_raw_paths(self) -> set[str]: ...
    async def reconcile_interrupted(self) -> None: ...
