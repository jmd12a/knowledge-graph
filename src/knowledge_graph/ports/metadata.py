from __future__ import annotations

from typing import Any, Protocol

from ..domain.source import Contribution


class MetadataPort(Protocol):
    """知识库配置、资料、任务及来源贡献协议；事务由适配器内部完成。"""

    async def ready(self) -> bool: ...
    async def kb(self, kb_id: str) -> dict[str, Any]: ...
    async def list_kbs(self) -> list[dict[str, Any]]: ...
    async def create_kb(self, name: str, model: dict, profile: dict) -> dict: ...

    async def document(self, kb_id: str, document_id: str) -> dict: ...
    async def document_exists(self, document_id: str) -> bool: ...
    async def documents(
        self, kb_id: str, active: bool | None = None, limit: int = 100, offset: int = 0
    ) -> list[dict]: ...
    async def list_documents(
        self, kb_id: str, active: bool | None = None, limit: int = 100, offset: int = 0
    ) -> list[dict]: ...
    async def active_documents(self, kb_id: str) -> list[dict]: ...
    async def document_jobs(self, kb_id: str, document_id: str, limit=100, offset=0) -> list[dict]: ...
    async def latest_extraction_job_id(self, kb_id: str) -> str | None: ...
    async def jobs_for_kb(self, kb_id: str) -> list[dict]: ...

    async def request(self, kb_id: str, operation: str, key: str) -> dict | None: ...
    async def register_upload(self, doc: dict, input_data: dict, key: str, request_data: dict) -> dict:
        """同一短事务登记资料、导入任务与幂等请求，返回实际登记结果。"""
        ...

    async def enqueue(
        self,
        kb_id: str,
        operation: str,
        document_id: str | None,
        input_data: dict,
        key: str,
        request_data: dict,
    ) -> str: ...
    async def job(self, job_id: str) -> dict: ...
    async def update_job(self, job_id: str, **fields: Any) -> None: ...
    async def maintenance(self, kb_id: str, state: str, job_id: str | None) -> None: ...
    async def claim(self, now: float, *, publication_only: bool = False) -> dict | None:
        """原子领取可执行任务；未完成写入的恢复任务优先于新任务。"""
        ...

    async def preparation_candidates(self, after: int, now: float, limit: int = 50) -> list[dict]: ...
    async def claim_preparation(self, observed: dict, now: float) -> dict | None: ...
    async def owns_preparation(self, job: dict) -> bool: ...
    async def update_preparation(self, job: dict, **fields: Any) -> bool: ...
    async def start_publication(self, job: dict) -> None: ...
    async def cancel_publication(self, job: dict) -> None: ...
    async def begin_publication_writes(self, job: dict) -> None: ...
    async def artifact_jobs(self, job_ids: list[str]) -> dict[str, dict]: ...

    async def retry(self, job_id: str, generation: int) -> bool: ...

    async def contributions(
        self, kb_id: str, document_ids: list[str] | None = None, *, contribution_ids: list[str] | None = None
    ) -> list[Contribution]:
        """按来源和贡献 ID 取交集，供合并、范围查询及证据回查。"""
        ...

    async def target_contributions(
        self, kb_id: str, targets: list[tuple[str, str]], *, active_only: bool = False
    ) -> list[Contribution]: ...
    async def contribution_count(self, kb_id: str) -> int: ...

    async def replace_contributions(
        self, kb_id: str, contributions: list[Contribution], issues: list[dict], issue_documents: list[str],
        *, document_ids: list[str] | None = None,
    ) -> None:
        """None 替换全库贡献；列表仅替换指定来源，其他来源保持不变。"""
        ...
    async def vector_members(
        self, kb_id: str, *, chunk_ids=None, document_ids=None, vector_ids=None, domain_ids=None, active_only=False
    ) -> list[dict]: ...
    async def replace_vector_members(self, kb_id: str, vector_ids: list[str] | None, members: list[dict]) -> None: ...
    async def finish(self, job_id: str, plan: dict) -> bool:
        """提交可查询状态，返回删除任务是否还有物理清理。"""
        ...

    async def candidate_issues(self, job_id: str, limit: int, offset: int) -> list[dict]: ...

    async def expired_checkpoints(self, threshold: str) -> list[dict]: ...
    async def referenced_raw_paths(self) -> set[str]: ...
    async def reconcile_interrupted(self, *, publication_only: bool = False) -> None: ...
