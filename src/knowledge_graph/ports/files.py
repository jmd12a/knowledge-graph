from __future__ import annotations

from pathlib import Path
from typing import Protocol

from ..domain.model import BusinessModel
from ..domain.source import ParsedDocument


class ContentReader(Protocol):
    async def read(self, size: int) -> bytes: ...
    async def close(self) -> None: ...


class FilesPort(Protocol):
    """保存原文、上传暂存与可恢复写入计划。"""

    root: Path

    def initialize(self) -> None: ...
    def exists(self, path: str | Path) -> bool: ...
    def read_json(self, path: str | Path) -> dict | None: ...
    def job_checkpoints(self, job_id: str) -> list[dict]: ...
    def orphan_files(self, referenced_paths: set[str], cutoff: float) -> list[str]: ...

    async def stage_upload(self, upload, max_bytes: int) -> dict:
        """流式暂存并执行字节上限检查，返回 path 与 byte_length。"""
        ...

    async def open_content(self, path: str, expected_bytes: int) -> ContentReader:
        """打开并核对预期长度；调用方负责关闭返回的读取器。"""
        ...

    def publish_upload(self, temp_path: str, kb_id: str, document_id: str, extension: str) -> str:
        """将已暂存原文发布到资料目录，返回登记元数据所用路径。"""
        ...

    def path(self, *parts: str) -> Path: ...
    def raw_path(self, kb_id: str, document_id: str, extension: str) -> Path: ...

    def job_dir(self, job_id: str) -> Path: ...
    def atomic(self, path: Path, value: dict) -> None:
        """原子替换 JSON 文件，供检查点与写入计划持久化使用。"""
        ...

    def attempt_dir(self, job: dict) -> Path: ...
    def begin_preparation(self, job: dict) -> None: ...
    def read_preparation(self, job: dict) -> dict | None: ...
    def extraction_path(self, job: dict) -> Path: ...
    def parse_document(self, parser: ParserPort, document: dict, model: BusinessModel) -> ParsedDocument: ...
    def save_plan(self, job_id: str, plan: dict, *, path: Path | None = None) -> str: ...
    def read_plan(self, job: dict) -> dict: ...
    def same_bytes(self, first: Path, second: Path) -> bool: ...
    def remove(self, path: str) -> None: ...


class ParserPort(Protocol):
    def parse(self, doc: dict, model: BusinessModel) -> ParsedDocument: ...
